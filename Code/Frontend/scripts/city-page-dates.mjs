#!/usr/bin/env node
/**
 * city-page-dates.mjs — writes src/data/city-page-dates.ts from git history.
 *
 * WHY
 * ---
 * /solar-savings/<city> and the older /solar-companies/<city> template render
 * from src/data/cities-data.ts, which carries no date field. Their metadata
 * hard-coded one publish date for every city ('2026-04-14'), a day before most
 * of those cities existed, and no modified date at all. The /solar-cost and
 * comparison pages already show a dated byline, so the older pages could not
 * say when they were last changed without inventing a date.
 *
 * The repository already records that date. For each city entry this reads:
 *   added   — the first commit in which `slug: '<slug>'` appears in the file
 *   updated — the newest commit that changed a line of that entry's page copy
 * Lines that do not change what a reader sees are ignored: metaTitle,
 * metaDescription, ogTitle, ogDescription, seoData, energySageUrl,
 * googleSunroofUrl and relatedArticles. Dates are the commit author's own
 * calendar date (its recorded time zone), so nothing is estimated.
 *
 * Run it after committing a change to cities-data.ts, then commit the output:
 *   node scripts/city-page-dates.mjs
 * Uncommitted edits are reported and left out, so the file can only ever
 * understate how recent a change is.
 */

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = 'src/data/cities-data.ts';
const OUT = join(ROOT, 'src', 'data', 'city-page-dates.ts');

const git = (...args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

/** Author date in the author's own recorded offset, as YYYY-MM-DD. */
function localDate(epochSeconds, tz) {
  const sign = tz.startsWith('-') ? -1 : 1;
  const minutes = sign * (Number(tz.slice(1, 3)) * 60 + Number(tz.slice(3, 5)));
  return new Date((Number(epochSeconds) + minutes * 60) * 1000).toISOString().slice(0, 10);
}

// --- blame, line by line -----------------------------------------------------
const porcelain = git('blame', '--line-porcelain', '--', DATA).split('\n');
const commits = new Map();
const lines = [];
for (let i = 0; i < porcelain.length; i++) {
  const head = /^([0-9a-f]{40}) \d+ \d+/.exec(porcelain[i]);
  if (!head) continue;
  const sha = head[1];
  const info = commits.get(sha) ?? {};
  i++;
  while (i < porcelain.length && !porcelain[i].startsWith('\t')) {
    const space = porcelain[i].indexOf(' ');
    info[porcelain[i].slice(0, space)] = porcelain[i].slice(space + 1);
    i++;
  }
  commits.set(sha, info);
  lines.push({ sha, text: (porcelain[i] ?? '').slice(1) });
}

const UNCOMMITTED = '0000000000000000000000000000000000000000';
const NOT_PAGE_COPY = /^\s*(metaTitle|metaDescription|ogTitle|ogDescription|seoData|energySageUrl|googleSunroofUrl|relatedArticles)\b/;
const indentOf = (text) => text.length - text.trimStart().length;

const result = {};
let uncommitted = 0;
for (let k = 0; k < lines.length; k++) {
  const slugMatch = /^\s*slug: '([a-z0-9-]+)',/.exec(lines[k].text);
  if (!slugMatch) continue;
  const slug = slugMatch[1];
  let start = k;
  while (start > 0 && !/^\s*\{\s*$/.test(lines[start].text)) start--;
  const entryIndent = indentOf(lines[start].text);
  let end = k;
  while (end < lines.length - 1 && !(new RegExp(`^\\s{${entryIndent}}\\},?\\s*$`).test(lines[end].text))) end++;

  let skipping = false;
  let newest = null;
  for (let j = start; j <= end; j++) {
    const { sha, text } = lines[j];
    if (NOT_PAGE_COPY.test(text)) skipping = true;
    else if (/^\s*[A-Za-z]+:/.test(text) && indentOf(text) <= entryIndent + 4) skipping = false;
    if (skipping) continue;
    if (sha === UNCOMMITTED) { uncommitted++; continue; }
    const info = commits.get(sha);
    const date = localDate(info['author-time'], info['author-tz']);
    if (!newest || date > newest) newest = date;
  }

  const added = git('log', '--reverse', '--format=%ad', '--date=format:%Y-%m-%d', '-S', `slug: '${slug}'`, '--', DATA)
    .split('\n')
    .find(Boolean);
  result[slug] = { added, updated: newest && added && newest < added ? added : newest };
}

const body = Object.keys(result)
  .sort()
  .map((slug) => `  ${/^[a-z]+$/.test(slug) ? slug : `'${slug}'`}: { added: '${result[slug].added}', updated: '${result[slug].updated}' },`)
  .join('\n');

writeFileSync(
  OUT,
  `// GENERATED by scripts/city-page-dates.mjs from the git history of
// src/data/cities-data.ts. Do not edit by hand; re-run the script after a
// committed change to a city entry.
//
// added:   the first commit that contains the city's entry
// updated: the newest commit that changed that entry's page copy (SEO-only
//          fields such as metaTitle are ignored)
// Both are the commit author's own calendar date. See the script for why these
// pages take their dates from version history rather than a typed field.

export interface CityPageDates {
  added: string;
  updated: string;
}

export const CITY_PAGE_DATES: Readonly<Record<string, CityPageDates>> = {
${body}
};
`,
);
console.log(`city-page-dates: ${Object.keys(result).length} cities written to src/data/city-page-dates.ts`);
if (uncommitted) console.log(`note: ${uncommitted} uncommitted line(s) ignored; commit and re-run to include them`);
